"""Rain-gauge measurement model."""

from __future__ import annotations

from datetime import datetime
from decimal import Decimal

from sqlalchemy import (
    DateTime,
    ForeignKey,
    Index,
    Numeric,
    String,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import PRIMARY_KEY_TYPE, Base


class Measurement(Base):
    """A single rainfall reading reported by a sensor via a bridge.

    ``sent_at`` is the device transmit time (epoch seconds converted to naive
    UTC). ``recorded_at`` is generated by the database on insert, so it is the
    authoritative "when it reached the database" timestamp.

    The unique constraint on ``(sensor_id, sent_at)`` makes the write
    idempotent: LoRa links retransmit, and a repeated packet must not create a
    second row. It also serves as the index for filtering by sensor.
    """

    __tablename__ = "measurements"
    __table_args__ = (
        UniqueConstraint("sensor_id", "sent_at", name="uq_measurements_sensor_sent"),
        Index("ix_measurements_bridge_sent", "bridge_id", "sent_at"),
        {"mysql_charset": "utf8mb4", "mysql_collate": "utf8mb4_unicode_ci"},
    )

    id: Mapped[int] = mapped_column(PRIMARY_KEY_TYPE, primary_key=True, autoincrement=True)
    bridge_id: Mapped[str] = mapped_column(
        String(64), ForeignKey("bridges.bridge_id"), nullable=False
    )
    sensor_id: Mapped[str] = mapped_column(String(64), nullable=False)
    value_mm: Mapped[Decimal] = mapped_column(Numeric(6, 2), nullable=False)
    sent_at: Mapped[datetime] = mapped_column(DateTime, nullable=False)
    recorded_at: Mapped[datetime] = mapped_column(
        DateTime, nullable=False, server_default=func.now()
    )

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return (
            f"<Measurement bridge={self.bridge_id!r} sensor={self.sensor_id!r} "
            f"value_mm={self.value_mm} sent_at={self.sent_at}>"
        )
