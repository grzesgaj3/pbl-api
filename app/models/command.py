"""Rain-gauge cleaning command model and its status enum."""

from __future__ import annotations

import enum
from datetime import datetime

from sqlalchemy import DateTime, Enum, ForeignKey, Index, String, func
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class CommandStatus(str, enum.Enum):
    """Lifecycle of a cleaning command."""

    PENDING = "PENDING"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    REJECTED = "REJECTED"


class Command(Base):
    """A request to clean a rain gauge, addressed to a single bridge.

    The admin creates the command; the target bridge fetches it, forwards the
    LoRa payload (e.g. ``sensor1;clean;``) to the field network and then either
    acknowledges or rejects it. ``payload`` is generated by the API so the
    on-air format stays in one place.
    """

    __tablename__ = "commands"
    __table_args__ = (
        Index("ix_commands_bridge_status_created", "bridge_id", "status", "created_at"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    bridge_id: Mapped[str] = mapped_column(
        String(64), ForeignKey("bridges.bridge_id"), nullable=False, index=True
    )
    sensor_id: Mapped[str | None] = mapped_column(String(64), nullable=True)
    command_type: Mapped[str] = mapped_column(
        String(32), nullable=False, default="clean", server_default="clean"
    )
    payload: Mapped[str] = mapped_column(String(255), nullable=False)
    status: Mapped[CommandStatus] = mapped_column(
        Enum(CommandStatus, name="command_status", native_enum=True),
        nullable=False,
        default=CommandStatus.PENDING,
        server_default=CommandStatus.PENDING.value,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime, nullable=False, server_default=func.now()
    )
    responded_at: Mapped[datetime | None] = mapped_column(DateTime, nullable=True)
    response_note: Mapped[str | None] = mapped_column(String(255), nullable=True)

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return (
            f"<Command id={self.id} bridge={self.bridge_id!r} "
            f"sensor={self.sensor_id!r} status={self.status}>"
        )
